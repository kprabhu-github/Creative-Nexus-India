// POST /api/searchlens/fix/robots-txt
// Generates robots.txt content with explicit AI-crawler rules. Pure template
// — no LLM call needed; keeps cost zero and output deterministic.

import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";
import { createAdminClient } from "@/lib/supabase/admin";
import type { FixArtifact } from "@/lib/searchlens/fix-types";

const ORG_ID = "a0000000-0000-0000-0000-000000000001";
export const dynamic = "force-dynamic";

const Schema = z.object({
  domain: z.string().min(1).max(200),
  sitemap_url: z.string().url().optional(),
  rules: z
    .array(
      z.object({
        user_agent: z.string().trim().min(1).max(80),
        directive: z.enum(["allow", "disallow"]),
        path: z.string().trim().max(200).default("/"),
      }),
    )
    .min(1)
    .max(40),
  baseline_disallow: z.array(z.string().trim().max(200)).max(20).optional(),
  cms: z.string().trim().max(40).optional(),
});

function render(input: z.infer<typeof Schema>): string {
  const lines: string[] = [];

  // Baseline default — every other user-agent
  lines.push("# Auto-generated by Creative Nexus / AI SearchLens");
  lines.push(`# Domain: ${input.domain}`);
  lines.push("");
  lines.push("User-agent: *");
  lines.push("Allow: /");
  for (const p of input.baseline_disallow ?? []) {
    lines.push(`Disallow: ${p}`);
  }
  lines.push("");

  // Per-crawler rules
  for (const r of input.rules) {
    lines.push(`User-agent: ${r.user_agent}`);
    if (r.directive === "allow") lines.push(`Allow: ${r.path || "/"}`);
    else lines.push(`Disallow: ${r.path || "/"}`);
    lines.push("");
  }

  if (input.sitemap_url) {
    lines.push(`Sitemap: ${input.sitemap_url}`);
  }

  return lines.join("\n").trim() + "\n";
}

export async function POST(req: NextRequest) {
  const body = (await req.json().catch(() => ({}))) as unknown;
  const parsed = Schema.safeParse(body);
  if (!parsed.success) {
    return NextResponse.json(
      { error: "Invalid input", details: parsed.error.flatten() },
      { status: 400 },
    );
  }
  const p = parsed.data;

  const output = render(p);

  const supabase = createAdminClient();
  const { data, error } = await supabase
    .from("ais_fix_artifacts")
    .insert({
      org_id: ORG_ID,
      kind: "robots_txt",
      title: `robots.txt for ${p.domain}`,
      input_json: p as unknown as Record<string, unknown>,
      output_text: output,
      output_format: "text",
      deployment_target: p.cms ?? null,
      source_url: p.domain,
    })
    .select("*")
    .single();

  if (error || !data) {
    return NextResponse.json(
      { error: error?.message ?? "Insert failed" },
      { status: 500 },
    );
  }
  return NextResponse.json(
    { data: { artifact: data as FixArtifact } },
    { status: 201 },
  );
}
